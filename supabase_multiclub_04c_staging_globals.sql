-- SOLO ENSAYO 04C. Estructura de supabase_global_players.sql, sin
-- bootstrap ni migraciones de datos del Caudal. Ejecutar tras legacy base.
begin;
do $guard$
begin
  if auth.uid() is not null or current_user <> 'postgres'
    or (select count(*) from auth.users) <> 0
    or to_regclass('public.players_database') is not null
    or to_regclass('public.jugadores') is null
    or exists (select 1 from public.jugadores)
    or exists (select 1 from public.equipos_rivales) then
    raise exception '04C exige proyecto nuevo sin datos deportivos';
  end if;
end $guard$;
create extension if not exists pg_trgm with schema extensions;
set local search_path = public, extensions;

create table if not exists public.players_database (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  photo_url text,
  dob date,
  age text,
  height text,
  foot text,
  scouting_summary varchar(500),
  scouting_priority text,
  card_alert boolean not null default false,
  sent_off_alert boolean not null default false,
  suspended_alert boolean not null default false,
  injured_alert boolean not null default false,
  external_source text,
  external_player_id text,
  field_sources jsonb not null default '{}'::jsonb,
  legacy_origin_id uuid unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.players_database add column if not exists age text;
alter table public.players_database add column if not exists scouting_priority text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'players_database_scouting_priority_check') then
    alter table public.players_database add constraint players_database_scouting_priority_check
      check (scouting_priority is null or scouting_priority in ('very_high', 'high', 'medium', 'low'));
  end if;
end $$;

create unique index if not exists players_database_external_identity_uidx
on public.players_database (lower(external_source), external_player_id)
where external_source is not null and external_player_id is not null;

create index if not exists players_database_name_idx
on public.players_database (lower(name));


create table if not exists public.player_team_memberships (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null references public.players_database(id) on delete cascade,
  team_id uuid not null references public.equipos_rivales(id) on delete cascade,
  season text,
  start_date date,
  end_date date,
  is_current boolean not null default true,
  number text,
  captain boolean not null default false,
  is_key boolean not null default false,
  observed boolean not null default false,
  squad_role text,
  tactical_role text,
  tactical_slot integer,
  tactical_reserve_slot integer,
  source_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint player_team_memberships_role_check check (tactical_role is null or tactical_role in ('Titular', 'Reserva')),
  constraint player_team_memberships_slot_check check (tactical_slot is null or tactical_slot between 0 and 10),
  constraint player_team_memberships_reserve_slot_check check (tactical_reserve_slot is null or tactical_reserve_slot between 0 and 1),
  constraint player_team_memberships_placement_check check (
    (tactical_role is null and tactical_slot is null and tactical_reserve_slot is null)
    or (tactical_role = 'Titular' and tactical_slot is not null and tactical_reserve_slot is null)
    or (tactical_role = 'Reserva' and tactical_slot is not null and tactical_reserve_slot is not null)
  )
);

create unique index if not exists player_team_memberships_current_stage_uidx
on public.player_team_memberships (player_id, team_id)
where is_current;

-- El proyecto trabaja con un único club actual. Si una versión anterior dejó dos,
-- conserva la etapa más reciente y cierra las demás sin borrar historial.
create unique index if not exists player_team_memberships_one_current_player_uidx
on public.player_team_memberships (player_id)
where is_current;

create index if not exists player_team_memberships_team_current_idx
on public.player_team_memberships (team_id, is_current);

create unique index if not exists player_team_memberships_starter_slot_uidx
on public.player_team_memberships (team_id, tactical_slot)
where is_current and tactical_role = 'Titular' and tactical_slot is not null;

create unique index if not exists player_team_memberships_reserve_slot_uidx
on public.player_team_memberships (team_id, tactical_slot, tactical_reserve_slot)
where is_current and tactical_role = 'Reserva' and tactical_slot is not null and tactical_reserve_slot is not null;

create table if not exists public.player_positions (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players_database(id) on delete cascade,
  position_type text not null check (position_type in ('natural', 'specific')),
  position_key text not null,
  is_primary boolean not null default false,
  source text not null default 'manual',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint player_positions_key_check check (
    (position_type = 'natural' and position_key in ('goalkeeper', 'defender', 'midfielder', 'forward'))
    or (position_type = 'specific' and position_key in (
      'goalkeeper', 'sweeper_keeper', 'right_back', 'left_back', 'right_wing_back', 'left_wing_back',
      'centre_back', 'right_centre_back', 'left_centre_back', 'libero', 'holding_midfield',
      'defensive_midfield', 'central_midfield', 'right_central_midfield', 'left_central_midfield',
      'attacking_midfield', 'right_midfield', 'left_midfield', 'right_winger', 'left_winger',
      'second_striker', 'centre_forward', 'mobile_forward', 'target_forward'
    ))
  ),
  unique (player_id, position_type, position_key)
);

create unique index if not exists player_positions_one_primary_per_type_uidx
on public.player_positions (player_id, position_type)
where is_primary;

create index if not exists player_positions_key_idx
on public.player_positions (position_type, position_key, player_id);

create table if not exists public.player_sources (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players_database(id) on delete cascade,
  url text not null,
  source_name text not null default 'Otro',
  is_primary boolean not null default false,
  analysis_status text not null default 'not_analyzed',
  analyzed_at timestamptz,
  analysis_error text,
  analysis_summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (player_id, url),
  constraint player_sources_analysis_status_check check (analysis_status in ('not_analyzed', 'analyzing', 'data_found', 'no_data', 'access_error', 'not_player'))
);

alter table public.player_sources
  add column if not exists analysis_status text not null default 'not_analyzed',
  add column if not exists analyzed_at timestamptz,
  add column if not exists analysis_error text,
  add column if not exists analysis_summary jsonb not null default '{}'::jsonb;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'player_sources_analysis_status_check') then
    alter table public.player_sources add constraint player_sources_analysis_status_check
      check (analysis_status in ('not_analyzed', 'analyzing', 'data_found', 'no_data', 'access_error', 'not_player'));
  end if;
end $$;

create unique index if not exists player_sources_one_primary_uidx
on public.player_sources (player_id)
where is_primary;

create table if not exists public.player_scouting_traits (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players_database(id) on delete cascade,
  category text not null check (category in ('strength', 'vulnerability', 'trend')),
  label text not null,
  position_family text,
  created_at timestamptz not null default now(),
  unique (player_id, category, label)
);

create table if not exists public.legacy_rival_player_migration (
  legacy_player_id uuid primary key references public.jugadores_rivales(id) on delete cascade,
  global_player_id uuid not null references public.players_database(id) on delete cascade,
  membership_id uuid references public.player_team_memberships(id) on delete set null,
  match_basis text not null default 'legacy_row',
  review_status text not null default 'pending' check (review_status in ('pending', 'confirmed', 'possible_duplicate')),
  created_at timestamptz not null default now()
);

create table if not exists public.legacy_own_player_migration (
  legacy_player_id uuid primary key references public.jugadores(id) on delete cascade,
  global_player_id uuid not null references public.players_database(id) on delete cascade,
  membership_id uuid references public.player_team_memberships(id) on delete set null,
  match_basis text not null,
  review_status text not null default 'confirmed' check (review_status in ('confirmed', 'possible_duplicate', 'pending')),
  possible_duplicate_id uuid references public.players_database(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.player_merge_history (
  id bigint generated by default as identity primary key,
  kept_player_id uuid not null,
  merged_player_id uuid not null,
  merged_snapshot jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.jugadores_rivales
  add column if not exists global_player_id uuid references public.players_database(id) on delete set null,
  add column if not exists membership_id uuid references public.player_team_memberships(id) on delete set null;

-- La fila histórica de Plantilla conserva su UUID y todas sus relaciones. Estos
-- campos solo la enlazan con el perfil canónico y con su etapa actual.
alter table public.jugadores
  add column if not exists global_player_id uuid references public.players_database(id) on delete set null,
  add column if not exists membership_id uuid references public.player_team_memberships(id) on delete set null,
  add column if not exists active_in_squad boolean not null default true;

create index if not exists jugadores_global_player_id_idx
on public.jugadores (global_player_id)
where global_player_id is not null;

create index if not exists jugadores_active_in_squad_idx
on public.jugadores (active_in_squad, global_player_id);

alter table public.equipo_rival_alineacion
  add column if not exists global_player_id uuid references public.players_database(id) on delete set null,
  add column if not exists membership_id uuid references public.player_team_memberships(id) on delete set null;

alter table public.equipo_rival_banquillo
  add column if not exists global_player_id uuid references public.players_database(id) on delete set null,
  add column if not exists membership_id uuid references public.player_team_memberships(id) on delete set null;

alter table public.partido_alineacion_slots
  add column if not exists global_player_id uuid references public.players_database(id) on delete set null,
  add column if not exists membership_id uuid references public.player_team_memberships(id) on delete set null;

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists players_database_touch_updated_at on public.players_database;
create trigger players_database_touch_updated_at before update on public.players_database
for each row execute function public.touch_updated_at();

drop trigger if exists player_team_memberships_touch_updated_at on public.player_team_memberships;
create trigger player_team_memberships_touch_updated_at before update on public.player_team_memberships
for each row execute function public.touch_updated_at();

drop trigger if exists player_positions_touch_updated_at on public.player_positions;
create trigger player_positions_touch_updated_at before update on public.player_positions
for each row execute function public.touch_updated_at();


alter table public.players_database enable row level security;
alter table public.player_team_memberships enable row level security;
alter table public.player_positions enable row level security;
alter table public.player_sources enable row level security;
alter table public.player_scouting_traits enable row level security;
alter table public.legacy_rival_player_migration enable row level security;
alter table public.legacy_own_player_migration enable row level security;
alter table public.player_merge_history enable row level security;

do $$
declare table_name text;
begin
  foreach table_name in array array['players_database', 'player_team_memberships', 'player_positions', 'player_sources', 'player_scouting_traits', 'legacy_rival_player_migration', 'legacy_own_player_migration', 'player_merge_history']
  loop
    execute format('drop policy if exists "Authenticated staff can read %s" on public.%I', table_name, table_name);
    execute format('create policy "Authenticated staff can read %s" on public.%I for select to authenticated using (true)', table_name, table_name);
    execute format('drop policy if exists "Authenticated staff can insert %s" on public.%I', table_name, table_name);
    execute format('create policy "Authenticated staff can insert %s" on public.%I for insert to authenticated with check (true)', table_name, table_name);
    execute format('drop policy if exists "Authenticated staff can update %s" on public.%I', table_name, table_name);
    execute format('create policy "Authenticated staff can update %s" on public.%I for update to authenticated using (true) with check (true)', table_name, table_name);
    execute format('drop policy if exists "Authenticated staff can delete %s" on public.%I', table_name, table_name);
    execute format('create policy "Authenticated staff can delete %s" on public.%I for delete to authenticated using (true)', table_name, table_name);
  end loop;
end $$;

comment on table public.players_database is 'Fuente única del perfil estable del futbolista, independiente de su club.';
comment on table public.player_team_memberships is 'Etapas históricas del futbolista en equipos rivales; una vuelta al mismo club crea una etapa nueva.';
comment on table public.player_positions is 'Posiciones naturales y específicas múltiples, con principal explícita y origen por posición.';
comment on table public.player_sources is 'Referencias acumulativas del jugador; añadir una fuente nunca sustituye las anteriores.';
comment on table public.player_scouting_traits is 'Fortalezas, vulnerabilidades y tendencias observables del futbolista.';
comment on table public.legacy_own_player_migration is 'Enlace reversible entre el UUID histórico de Plantilla y el perfil global del futbolista.';


-- Grants solo de ensayo para reproducir el acceso authenticated legacy.
revoke all on table public.players_database, public.player_team_memberships,
  public.player_positions, public.player_sources, public.player_scouting_traits,
  public.legacy_rival_player_migration, public.legacy_own_player_migration,
  public.player_merge_history from public, anon, authenticated;
grant select, insert, update, delete on table public.players_database,
  public.player_team_memberships, public.player_positions, public.player_sources,
  public.player_scouting_traits, public.legacy_rival_player_migration,
  public.legacy_own_player_migration, public.player_merge_history to authenticated;
commit;
